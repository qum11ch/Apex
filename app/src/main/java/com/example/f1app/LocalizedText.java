package com.example.f1app;

public class LocalizedText {
    private String ru;
    private String en;

    public LocalizedText() {
    }

    public String getRu() {
        return ru;
    }

    public void setRu(String ru) {
        this.ru = ru;
    }

    public String getEn() {
        return en;
    }

    public void setEn(String en) {
        this.en = en;
    }
}